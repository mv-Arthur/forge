export function detailFloorAreaHint(floor?: string): string {
    if (!floor) return DETAIL_FLOOR_AREA;
    const n = floor.match(/^(\d+)\s*этаж/i);
    if (n) return `Площадь ${n[1]} этажа`;
    return `Площадь ${floor}`;
}

