export interface MoscowDistrict {
    id: string;
    name: string;
    okrug: string;
    query: string;
}

function rayon(okrug: string, name: string): MoscowDistrict {
    return {
        id: `${okrug}-${name}`.toLowerCase().replaceAll(" ", "-"),
        name,
        okrug,
        query: `Москва, район ${name}`,
    };
}

function poselenie(okrug: string, name: string): MoscowDistrict {
    return {
        id: `${okrug}-${name}`.toLowerCase().replaceAll(" ", "-"),
        name,
        okrug,
        query: `Москва, поселение ${name}`,
    };
}

